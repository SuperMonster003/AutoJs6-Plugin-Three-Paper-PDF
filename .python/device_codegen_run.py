"""Runs the scripts the tools generate (Rhino, Node.js, Bun) on a device and checks what they leave (3-Paper PDF roadmap
P6.13 and P6.15, checkpoint 11).

Usage: py -3.12 -I .python/device_codegen_run.py -s SERIAL --export DIR [--styles rhino,node,bun] [--timeout SECONDS]
       [--keep]

1. DIR is written by the opt-in unit test ScriptDeviceExportTest (environment variable PAPER_CODEGEN_EXPORT=DIR,
   `gradlew :app:testDebugUnitTest --tests "*ScriptDeviceExportTest"`): the 13 tools in the three styles, generated by
   codegen/ScriptGenerator for fixtures under /sdcard/Documents/3-Paper PDF/codegen/in/, and manifest.json with the
   output every script must leave and the passwords to fill in.
2. The host (6.8.1 with the version 2 methods), 3-Paper PDF 1.1.0, Node.js Runtime 2.2.0 and Bun Runtime 0.23.0 (API
   33 or later) must already be installed and enabled, the host allowed to read and write shared storage. A style whose
   runtime is missing is reported SKIP. The tool installs nothing and answers no dialog.
3. The fixtures go to .../codegen/in/, a host script renders the two pictures of from-images there; for Bun the grant
   pdf.control is set for the run through a host script and put back afterwards. Every script gets its password
   placeholders filled in (`let password = null;` and `let newPassword = null;`), runs through RunIntentActivity (a
   Node.js script as its project folder with the generated project.json) and must leave its output within the timeout
   (default 90 s). A host script then checks every output against the manifest (page count, rotations, the encryption,
   a text on the last page, a smaller size, form values, the title and the outline, the number of files) and writes the
   verdicts to a file, so the check does not depend on logcat.
4. .../codegen/ is removed afterwards unless --keep is given.
One line per script: PASS / FAIL / SKIP, style, tool and key values; the exit code is 1 when a check failed.

zh-CN: 在设备上运行工具生成的脚本 (Rhino, Node.js, Bun) 并核对它们的产物 (3-Paper PDF 路线图 P6.13 与 P6.15, 检查点 11). 1. DIR 由按需运行的单测
ScriptDeviceExportTest 写出 (环境变量 PAPER_CODEGEN_EXPORT=DIR, `gradlew :app:testDebugUnitTest --tests "*ScriptDeviceExportTest"`): 13 个工具三种写法,
由 codegen/ScriptGenerator 针对 /sdcard/Documents/3-Paper PDF/codegen/in/ 下的样例生成, manifest.json 列出每个脚本须留下的产物与要填入的密码.
2. 宿主 (带版本 2 方法的 6.8.1), 3-Paper PDF 1.1.0, Node.js Runtime 2.2.0 与 Bun Runtime 0.23.0 (API 33 或以上) 须已安装并启用, 宿主有共享存储读写
权限. 缺少运行时的写法报 SKIP. 本工具不安装任何东西, 不应答对话框. 3. 样例推到 .../codegen/in/, 由宿主脚本在那里渲染 from-images 用的两张图; Bun
运行期间经宿主脚本设置 pdf.control 授权, 结束后恢复. 每个脚本先填入密码占位 (`let password = null;` 与 `let newPassword = null;`), 再经 RunIntentActivity
运行 (Node.js 脚本以带生成的 project.json 的项目文件夹运行), 须在超时 (默认 90 秒) 内留下产物. 之后由宿主脚本按清单核对每个产物 (页数, 旋转, 加密,
最后一页的文字, 体积变小, 表单值, 标题与大纲, 文件数) 并把结论写进文件, 不依赖 logcat. 4. 结束后删除 .../codegen/, 给出 --keep 时保留.
每个脚本输出一行: PASS / FAIL / SKIP, 写法, 工具与关键数值; 有检查失败时退出码为 1.
"""
import argparse
import json
import re
import shlex
import subprocess
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
HOST = "org.autojs.autojs6"
PLUGIN = "io.github.supermonster003.autojs6.plugin.three.paper.pdf"
NODE = "io.github.supermonster003.autojs6.plugin.nodejs"
BUN = "io.github.supermonster003.autojs6.plugin.bun.runtime"
RUN_ACTIVITY = f"{HOST}/org.autojs.autojs.external.open.RunIntentActivity"
BASE = "/storage/emulated/0/Documents/3-Paper PDF/codegen"
INPUT = f"{BASE}/in"
SCRIPTS = f"{BASE}/scripts"
FIXTURES = ("text.pdf", "outline.pdf", "encrypted.pdf", "form.pdf", "scanned-multi.pdf")

PREP_JS = """
var IN = @@IN@@, OUT = @@OUT@@;
var r = {};
try {
    r.png = pdf.renderToFile(IN + '/text.pdf', 1, IN + '/page-1.png', { dpi: 72 }).path;
    r.jpg = pdf.renderToFile(IN + '/outline.pdf', 1, IN + '/page-2.jpg', { dpi: 72, format: 'jpeg' }).path;
} catch (e) {
    r.error = String(e.code || '') + ' ' + String(e.message || e).slice(0, 200);
}
files.write(OUT, JSON.stringify(r));
"""

GRANT_JS = """
var OUT = @@OUT@@, VALUE = @@VALUE@@;
var r = {};
try {
    var key = org.autojs.autojs.core.pref.keys.CredentialKeys.BUN_HOST_CAPABILITY_GRANT.key('pdf.control');
    var before = key.storedOrNull();
    r.before = before === null ? 'absent' : String(before);
    if (VALUE === 'absent') key.set(null, true); else key.set(java.lang.Boolean.valueOf(VALUE === 'true'), true);
    r.after = key.storedOrNull() === null ? 'absent' : String(key.storedOrNull());
} catch (e) {
    r.error = String(e.message || e).slice(0, 200);
}
files.write(OUT, JSON.stringify(r));
"""

# Checks every output of the manifest; the verdicts go to OUT. zh-CN: 按清单核对每个产物; 结论写到 OUT.
VERIFY_JS = """
var ENTRIES = @@ENTRIES@@, IN = @@IN@@, OUT = @@OUT@@;
function codeOf(body) {
    try {
        body();
        return 'OK';
    } catch (e) {
        return String(e.code || e.message || e);
    }
}
var verdicts = [];
ENTRIES.forEach(function (entry) {
    var x = entry.expect, problems = [], notes = [];
    try {
        if (x.type === 'pdf') {
            var options = x.password ? { password: x.password } : undefined;
            var info = pdf.info(x.path, options);
            if (info.pageCount !== x.pages) problems.push('pages ' + info.pageCount + ' != ' + x.pages);
            notes.push('pages=' + info.pageCount);
            if (x.password) {
                var without = codeOf(function () { pdf.info(x.path); });
                if (without !== 'PASSWORD_REQUIRED') problems.push('without password ' + without);
                notes.push('locked');
            }
            if (x.encrypted === false && info.encrypted !== false) problems.push('still encrypted');
            if (x.rotations) {
                var rotations = info.pages.map(function (p) { return p.rotation; }).join(',');
                if (rotations !== x.rotations) problems.push('rotations ' + rotations);
                notes.push('rotations=' + rotations);
            }
            if (x.lastPageText && pdf.text(x.path, { pages: String(x.pages) })[0].indexOf(x.lastPageText) < 0) problems.push('no ' + x.lastPageText);
            if (x.smallerThan) {
                var before = new java.io.File(IN + '/' + x.smallerThan).length(), after = new java.io.File(x.path).length();
                if (!(after < before)) problems.push('not smaller ' + after + ' >= ' + before);
                notes.push(before + '->' + after + 'B');
            }
            if (x.fields) {
                var values = {};
                pdf.forms(x.path).forEach(function (f) { values[f.name] = f.value; });
                Object.keys(x.fields).forEach(function (name) {
                    if (values[name] !== x.fields[name]) problems.push(name + '=' + JSON.stringify(values[name]));
                });
            }
            if (x.title !== undefined && info.title !== x.title) problems.push('title ' + info.title);
            if (x.outline !== undefined && pdf.outline(x.path).length !== x.outline) problems.push('outline ' + pdf.outline(x.path).length);
        } else if (x.type === 'dir') {
            var names = files.isDir(x.path) ? files.listDir(x.path).filter(function (n) { return files.isFile(x.path + '/' + n); }) : [];
            if (names.length !== x.count) problems.push('files ' + names.length + ' != ' + x.count);
            notes.push('files=' + names.length);
        } else if (x.type === 'text') {
            var text = files.exists(x.path) ? files.read(x.path) : '';
            if (text.indexOf(x.contains) < 0) problems.push('no ' + x.contains + ' (' + text.length + ' chars)');
            notes.push('chars=' + text.length);
        }
    } catch (e) {
        problems.push(String(e.code || '') + ' ' + String(e.message || e).slice(0, 160));
    }
    verdicts.push({ style: entry.style, tool: entry.tool, ok: problems.length === 0, problems: problems, notes: notes });
});
files.write(OUT, JSON.stringify(verdicts));
"""


def adb(serial, *args, check=True, timeout=300):
    result = subprocess.run(["adb", "-s", serial, *args], capture_output=True, text=True, encoding="utf-8",
                            errors="replace", timeout=timeout)
    if check and result.returncode != 0:
        raise RuntimeError(f"adb {' '.join(args[:3])} failed: {(result.stderr or result.stdout).strip()[:300]}")
    return result.stdout.strip()


def shell(serial, command, timeout=120):
    return adb(serial, "shell", command, check=False, timeout=timeout)


def quote(path):
    return shlex.quote(path)


def version(serial, package):
    match = re.search(r"versionCode=(\d+)", shell(serial, f"dumpsys package {package}"))
    return int(match.group(1)) if match else None


def front(serial):
    shell(serial, f"am force-stop {HOST}")
    found = shell(serial, f"cmd package query-activities --brief -a android.intent.action.MAIN -c android.intent.category.LAUNCHER {HOST}")
    activity = next((line.strip() for line in found.splitlines() if line.strip().startswith(HOST + "/") and "leakcanary" not in line), None)
    if activity is None:
        raise RuntimeError("the launcher activity of the host was not found")
    shell(serial, f"am start -f 0x10008000 -n {activity}")
    time.sleep(4)


def push_text(serial, text, remote, scratch):
    local = scratch / "push.tmp"
    local.write_text(text, encoding="utf-8", newline="\n")
    try:
        adb(serial, "push", str(local), remote)
    finally:
        local.unlink()


def run_script(serial, path):
    out = shell(serial, f"am start -n {RUN_ACTIVITY} -e path {quote(path)}")
    if "Error" in out:
        raise RuntimeError(out[:300])


def wait_file(serial, path, timeout):
    deadline = time.time() + timeout
    while time.time() < deadline:
        text = shell(serial, f"cat {quote(path)} 2>/dev/null")
        if text:
            return text
        time.sleep(2)
    return None


def host_script(serial, name, script, scratch, timeout=90):
    """Runs a host script that writes its answer to <name>.json; answers the parsed answer or None."""
    out = f"{BASE}/{name}.json"
    shell(serial, f"rm -f {quote(out)}")
    push_text(serial, script.replace("@@OUT@@", json.dumps(out)), f"{BASE}/{name}.js", scratch)
    run_script(serial, f"{BASE}/{name}.js")
    text = wait_file(serial, out, timeout)
    return json.loads(text) if text else None


def set_grant(serial, value, scratch):
    result = host_script(serial, "grant", GRANT_JS.replace("@@VALUE@@", json.dumps(value)), scratch, 60)
    if not result or "error" in result:
        raise RuntimeError(f"setting pdf.control failed: {result}")
    print(f"INFO bun grant pdf.control: {result['before']} -> {result['after']}", flush=True)
    return result["before"]


def output_ready(serial, expect):
    """True once the output of [expect] is complete (a file of stable size, or a folder with every file)."""
    path = expect["path"]
    if expect["type"] == "dir":
        names = shell(serial, f"ls {quote(path)} 2>/dev/null").split()
        return len([n for n in names if not n.endswith(".part") and not n.startswith(".")]) >= expect["count"]
    first = shell(serial, f"stat -c %s {quote(path)} 2>/dev/null")
    if not first.isdigit() or int(first) == 0:
        return False
    time.sleep(1.5)
    return shell(serial, f"stat -c %s {quote(path)} 2>/dev/null") == first


def fill(code, passwords):
    for name, value in passwords.items():
        pattern = re.compile(rf"\blet {re.escape(name)} = null;")
        code, count = pattern.subn(f"let {name} = {json.dumps(value)};", code)
        if count != 1:
            raise RuntimeError(f"placeholder {name} found {count} times")
    return code


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("-s", "--serial", required=True)
    parser.add_argument("--export", type=Path, required=True)
    parser.add_argument("--styles", default="rhino,node,bun")
    parser.add_argument("--timeout", type=int, default=90)
    parser.add_argument("--keep", action="store_true")
    args = parser.parse_args()
    serial = args.serial
    manifest = json.loads((args.export / "manifest.json").read_text(encoding="utf-8"))
    styles = [s.strip() for s in args.styles.split(",") if s.strip()]
    sdk = int(shell(serial, "getprop ro.build.version.sdk") or 0)
    versions = {name: version(serial, package) for name, package in (("host", HOST), ("plugin", PLUGIN), ("node", NODE), ("bun", BUN))}
    print(f"INFO device={shell(serial, 'getprop ro.product.model')} sdk={sdk} " + " ".join(f"{k}={v}" for k, v in versions.items()), flush=True)
    failed = 0
    skipped = set()
    if "node" in styles and versions["node"] is None:
        skipped.add("node")
    if "bun" in styles and (versions["bun"] is None or sdk < 33):
        skipped.add("bun")
    scratch = REPO / "build" / "device-codegen" / re.sub(r"[^A-Za-z0-9._-]", "_", serial)
    scratch.mkdir(parents=True, exist_ok=True)
    shell(serial, f"rm -rf {quote(BASE)}; mkdir -p {quote(INPUT)} {quote(SCRIPTS)}")
    grant_before = None
    try:
        for name in FIXTURES:
            adb(serial, "push", str(REPO / "samples" / "fixtures" / name), f"{INPUT}/{name}")
        front(serial)
        prep = host_script(serial, "prep", PREP_JS.replace("@@IN@@", json.dumps(INPUT)), scratch)
        if not prep or "error" in prep:
            print(f"FAIL prep {prep}", flush=True)
            return 1
        if "bun" in styles and "bun" not in skipped:
            grant_before = set_grant(serial, "true", scratch)
        ran = []
        for entry in manifest:
            style, tool = entry["style"], entry["tool"]
            if style not in styles:
                continue
            if style in skipped:
                print(f"SKIP {style} {tool} runtime not installed" + (f" or API {sdk} < 33" if style == "bun" else ""), flush=True)
                continue
            source = args.export / entry["script"]
            code = fill(source.read_text(encoding="utf-8"), entry["passwords"])
            if entry["project"]:
                folder = f"{SCRIPTS}/{style}/{tool}"
                shell(serial, f"mkdir -p {quote(folder)}")
                push_text(serial, (source.parent / "project.json").read_text(encoding="utf-8"), f"{folder}/project.json", scratch)
                remote = f"{folder}/main.js"
            else:
                shell(serial, f"mkdir -p {quote(SCRIPTS + '/' + style)}")
                remote = f"{SCRIPTS}/{style}/{tool}.js"
            push_text(serial, code, remote, scratch)
            started = time.time()
            run_script(serial, remote)
            ready = False
            while time.time() - started < args.timeout:
                if output_ready(serial, entry["expect"]):
                    ready = True
                    break
                time.sleep(2)
            if not ready:
                failed += 1
                print(f"FAIL {style} {tool} no output within {args.timeout} s ({entry['expect']['path']})", flush=True)
                continue
            ran.append(entry)
            print(f"INFO {style} {tool} output after {time.time() - started:.0f} s", flush=True)
        if ran:
            verdicts = host_script(serial, "verify", VERIFY_JS.replace("@@ENTRIES@@", json.dumps(ran)).replace("@@IN@@", json.dumps(INPUT)), scratch, 180)
            if verdicts is None:
                failed += 1
                print("FAIL verify no answer from the host script", flush=True)
            else:
                for v in verdicts:
                    failed += not v["ok"]
                    print(f"{'PASS' if v['ok'] else 'FAIL'} {v['style']} {v['tool']} {' '.join(v['notes'])}"
                          + ("" if v["ok"] else " problems=" + "; ".join(v["problems"])), flush=True)
    finally:
        if grant_before is not None:
            set_grant(serial, grant_before, scratch)
        if not args.keep:
            shell(serial, f"rm -rf {quote(BASE)}")
        for leftover in scratch.glob("*"):
            leftover.unlink()
        scratch.rmdir()
    print("PASS run" if failed == 0 else f"FAIL run ({failed})", flush=True)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
