/**
 * Turns a tool request into a complete script (roadmap P6.13, D51, D69) that does what the tool did, through the
 * script API of the host and the docs site: Rhino with synchronous `pdf.xxx(...)` calls, Node.js with the promises of
 * `require('pdf')` (the header lists the capabilities `project.json` declares), Bun with `host.pdf` after checking the
 * `pdf.control` grant. Option keys are the documented names of the script API, not the contract's. Passwords become
 * `null` placeholders the script refuses to run with; `warnings` are printed as the strings they are.
 * zh-CN: 把工具请求转为完整的脚本 (路线图 P6.13, D51, D69), 经宿主与文档站的脚本接口完成工具所做的事: Rhino 使用同步的 `pdf.xxx(...)`
 * 调用, Node.js 使用 `require('pdf')` 的 Promise 写法 (文件头列出 `project.json` 要声明的能力), Bun 在检查 `pdf.control` 授权后
 * 使用 `host.pdf`. 选项键使用脚本接口文档中的名称, 而不是契约的键. 密码替换为 `null` 占位, 未填写时脚本拒绝运行; `warnings` 按字符串
 * 原样打印.
 */
internal object ScriptGenerator {

    /** The start of every script's file name. zh-CN: 每个脚本文件名的开头. */
    const val FILE_PREFIX = "3-paper-"

    /** The Bun grant the PDF calls need. zh-CN: PDF 调用所需的 Bun 授权. */
    const val BUN_GRANT = "pdf.control"

    const val NODE_FILES = "files"

    const val NODE_FILES_WRITE = "files.write"

    fun generate(request: ScriptRequest, style: ScriptStyle): GeneratedScript {
        val body = Body(style)
        Writer(request, body).write()
        val name = FILE_PREFIX + request.kind.id
        val fileName = name + when (style) {
            ScriptStyle.RHINO -> GeneratedScript.RHINO_SUFFIX
            ScriptStyle.NODE -> GeneratedScript.NODE_SUFFIX
            ScriptStyle.BUN -> GeneratedScript.BUN_SUFFIX
        }
        val code = assemble(request, style, body)
        return GeneratedScript(style, code, fileName, if (style == ScriptStyle.NODE) projectJson(name, permissionsOf(request.kind)) else null)
    }

    /** The Node.js capabilities the script of [kind] uses. zh-CN: [kind] 的脚本使用的 Node.js 能力. */
    fun permissionsOf(kind: ToolKind): List<String> =
        if (kind == ToolKind.EXTRACT_TEXT) listOf(NODE_FILES) else listOf(NODE_FILES, NODE_FILES_WRITE)

    /** The `project.json` of a Node.js project folder. zh-CN: Node.js 项目文件夹的 `project.json`. */
    fun projectJson(name: String, permissions: List<String>): String = buildString {
        append("{\n")
        append("    \"name\": ").append(json(name)).append(",\n")
        append("    \"type\": \"node\",\n")
        append("    \"main\": ").append(json(GeneratedScript.NODE_MAIN)).append(",\n")
        append("    \"node\": {\n")
        append("        \"permissions\": ").append(permissions.joinToString(", ", "[", "]") { json(it) }).append("\n")
        append("    }\n")
        append("}\n")
    }

    /** English title of a tool, for the script's first line. zh-CN: 工具的英文标题, 用于脚本首行. */
    fun titleOf(kind: ToolKind): String = when (kind) {
        ToolKind.MERGE -> "Merge PDFs"
        ToolKind.SPLIT -> "Split a PDF"
        ToolKind.TO_IMAGES -> "PDF to images"
        ToolKind.FROM_IMAGES -> "Images to PDF"
        ToolKind.ENCRYPT -> "Encrypt a PDF"
        ToolKind.DECRYPT -> "Remove the password of a PDF"
        ToolKind.EXTRACT_TEXT -> "Extract text"
        ToolKind.ORGANIZE -> "Organize pages"
        ToolKind.WATERMARK -> "Add a watermark"
        ToolKind.PAGE_NUMBERS -> "Add page numbers, headers and footers"
        ToolKind.COMPRESS -> "Compress a PDF"
        ToolKind.FILL_FORM -> "Fill in a form"
        ToolKind.PROPERTIES -> "Edit the document properties"
    }

    private fun assemble(request: ScriptRequest, style: ScriptStyle, body: Body): String = buildString {
        when (style) {
            ScriptStyle.RHINO -> {}
            ScriptStyle.NODE -> append("\"nodejs\";\n\n")
            ScriptStyle.BUN -> append("\"bun\";\n\n")
        }
        append("// 3-Paper PDF: ").append(titleOf(request.kind)).append(".\n")
        append("// Generated by 3-Paper PDF from the last run of the tool. Check the paths before running it.\n")
        append("// Runs in AutoJs6 with the 3-Paper PDF plugin enabled in the Plugin Center.\n")
        when (style) {
            ScriptStyle.RHINO -> {}
            ScriptStyle.NODE -> {
                append("// Needs the Node.js runtime plugin. A project declares the capabilities this script uses in project.json:\n")
                append("// \"node\": { \"permissions\": ").append(permissionsOf(request.kind).joinToString(", ", "[", "]") { json(it) }).append(" }\n")
            }
            ScriptStyle.BUN -> {
                append("// Needs the Bun runtime plugin (Android 13 or later) with \"").append(BUN_GRANT).append("\" allowed in its settings in the Plugin Center.\n")
                append("// Bun ends a script after bun.timeoutMs (60 seconds unless project.json sets more); raise it for large documents.\n")
            }
        }
        if (body.passwords.isNotEmpty()) append("// Scripts never keep passwords: fill in the ones set to null below.\n")
        body.notes.forEach { append("// ").append(it).append('\n') }
        append('\n')
        body.helpers.forEach { append(it).append("\n\n") }
        if (style == ScriptStyle.RHINO) {
            body.lines.forEach { append(it).append('\n') }
            return@buildString
        }
        append("(async () => {\n")
        val pad = Js.INDENT
        if (style == ScriptStyle.NODE) {
            append(pad).append("let pdf = require('pdf');\n")
        } else {
            append(pad).append("let { createHostClient } = await import(process.env.AUTOJS6_HOST_CLIENT_MODULE);\n")
            append(pad).append("let host = await createHostClient();\n")
            append(pad).append("if (!host.hasCapability(").append(Js.string(BUN_GRANT)).append(")) {\n")
            append(pad).append(pad).append("throw new Error(").append(Js.string("Allow \"$BUN_GRANT\" for the Bun runtime in the Plugin Center first.")).append(");\n")
            append(pad).append("}\n")
            append(pad).append("let pdf = host.pdf;\n")
        }
        body.lines.forEach { append(it).append('\n') }
        append("})().catch((e) => {\n")
        append(pad).append("console.error(String(e));\n")
        append(pad).append("process.exitCode = 1;\n")
        append("});\n")
    }

    /** A JSON string; the names written are plain ASCII, only quotes, backslashes and controls need escapes. zh-CN: JSON 字符串. */
    private fun json(text: String): String = buildString {
        append('"')
        text.forEach { char ->
            when {
                char == '"' -> append("\\\"")
                char == '\\' -> append("\\\\")
                char.code < 0x20 -> append("\\u%04x".format(char.code))
                else -> append(char)
            }
        }
        append('"')
    }

    /**
     * The statements of a script body, at the nesting of its style (inside the async function for Node.js and Bun),
     * with the password placeholders, notes for the header and helper functions it needs.
     * zh-CN: 脚本主体的语句, 按写法的嵌套层级排版 (Node.js 与 Bun 在异步函数内), 另记录密码占位, 文件头说明与所需的辅助函数.
     */
    private class Body(val style: ScriptStyle) {

        val lines = ArrayList<String>()

        val passwords = ArrayList<String>()

        val notes = ArrayList<String>()

        val helpers = LinkedHashSet<String>()

        private var depth = if (style == ScriptStyle.RHINO) 0 else 1

        val await get() = if (style == ScriptStyle.RHINO) "" else "await "

        fun line(code: String) {
            lines += Js.INDENT.repeat(depth) + code
        }

        /** `let name = value;`, with [comment] at its end. zh-CN: `let name = value;`, 末尾带 [comment]. */
        fun let(name: String, value: Any?, comment: String? = null) {
            val head = Js.INDENT.repeat(depth) + "let $name = "
            val code = head + Js.format(value, depth, head.length, 1) + ";"
            lines += if (comment != null) "$code // $comment" else code
        }

        /** A path variable; a guessed path asks to be checked. zh-CN: 路径变量; 推测的路径会提示核对. */
        fun path(name: String, file: ScriptFile) = let(name, file.path, if (file.guessed) GUESSED else null)

        /** A list of paths; guessed ones are named in a comment above it. zh-CN: 路径列表; 推测的路径在其上方的注释中指出. */
        fun paths(name: String, files: List<ScriptFile>) {
            val guessed = files.withIndex().filter { it.value.guessed }.map { it.index + 1 }
            if (guessed.isNotEmpty()) line("// Check item${if (guessed.size > 1) "s" else ""} ${guessed.joinToString(", ")}: $GUESSED_LIST")
            let(name, files.map { it.path })
        }

        /** A password placeholder. zh-CN: 密码占位. */
        fun password(name: String, comment: String): Raw {
            passwords += name
            let(name, null, comment)
            return Raw(name)
        }

        /** Refuses to run while a placeholder is still null. zh-CN: 仍有占位为 null 时拒绝运行. */
        fun checkPasswords() {
            if (passwords.isEmpty()) return
            val condition = if (passwords.size == 1) "${passwords[0]} === null" else passwords.joinToString(", ", "[", "].indexOf(null) >= 0")
            line("if ($condition) {")
            indent { line("throw new Error(${Js.string("Fill in the password${if (passwords.size > 1) "s" else ""} set to null before running this script.")});") }
            line("}")
        }

        /**
         * `[let target = ][await ]callee(arguments);` (trailing null arguments dropped); [declare] false assigns a variable
         * declared before.
         * zh-CN: `[let target = ][await ]callee(arguments);` (去掉末尾的 null 参数); [declare] 为 false 时赋值给此前声明的变量.
         */
        fun call(target: String?, callee: String, arguments: List<Any?>, declare: Boolean = true) {
            val prefix = when {
                target == null -> ""
                declare -> "let $target = "
                else -> "$target = "
            } + await
            lines += Js.call(prefix, callee, arguments.dropLastWhile { it == null }, depth)
        }

        fun warnings(result: String) = line("$result.warnings.forEach((warning) => console.warn(warning));")

        fun indent(block: () -> Unit) {
            depth += 1
            block()
            depth -= 1
        }

        /** `try { block } finally { [await ]doc.close(); }`. zh-CN: `try { block } finally { [await ]doc.close(); }`. */
        fun closing(document: String, block: () -> Unit) {
            line("try {")
            indent(block)
            line("} finally {")
            indent { line("$await$document.close();") }
            line("}")
        }

    }

    /** Writes the statements of one tool. zh-CN: 写出一个工具的语句. */
    private class Writer(private val request: ScriptRequest, private val body: Body) {

        private val input = request.inputs.first()

        fun write() {
            when (val options = request.options) {
                is ToolOptions.Merge -> merge(options)
                is ToolOptions.Split -> split(options)
                is ToolOptions.ToImages -> toImages(options)
                is ToolOptions.FromImages -> fromImages(options)
                is ToolOptions.Encrypt -> encrypt()
                ToolOptions.Decrypt -> decrypt()
                is ToolOptions.ExtractText -> extractText(options)
                is ToolOptions.Organize -> organize(options)
                is ToolOptions.Watermark -> watermark(options)
                is ToolOptions.PageNumbers -> pageNumbers(options)
                is ToolOptions.Compress -> compress(options)
                is ToolOptions.FillForm -> fillForm(options)
                is ToolOptions.Properties -> properties(options)
            }
        }

        /** Declares the input, the output and the input's password; returns `{ password }` or nothing. zh-CN: 声明输入, 输出与输入的密码; 返回 `{ password }` 或空. */
        private fun single(): Map<String, Any?> {
            body.path("input", input.file)
            body.path(if (request.kind in FOLDER_KINDS) "outputDir" else "output", request.output)
            val password = if (input.password) body.password("password", PASSWORD_COMMENT) else null
            return if (password != null) mapOf(KEY_PASSWORD to password) else emptyMap()
        }

        private fun finish(result: String = "result") {
            body.warnings(result)
            body.line("console.log($result.path);")
        }

        private fun merge(options: ToolOptions.Merge) {
            body.paths("inputs", request.inputs.map { it.file })
            body.path("output", request.output)
            val passwords = request.inputs.mapIndexed { index, item ->
                if (item.password) body.password("password${index + 1}", "The password of item ${index + 1}. $FILL_IN") else null
            }
            body.checkPasswords()
            val opts = LinkedHashMap<String, Any?>()
            if (options.keepOutline) {
                opts["outline"] = PdfContract.OUTLINE_MERGE
                opts["displayNames"] = request.inputs.map { OutputNames.stem(it.name) }
            } else {
                opts["outline"] = PdfContract.OUTLINE_NONE
            }
            if (request.inputs.any { it.password }) opts["passwords"] = passwords
            body.call("result", "pdf.merge", listOf(Raw("inputs"), Raw("output"), opts))
            finish()
        }

        private fun split(options: ToolOptions.Split) {
            val opts = LinkedHashMap<String, Any?>()
            options.every?.let { opts["every"] = it }
            options.ranges?.let { opts["ranges"] = it }
            opts += single()
            body.checkPasswords()
            body.notes += "The parts are named <name>-1.pdf, <name>-2.pdf and so on (the tool pads the numbers: <name>-01.pdf)."
            body.call("result", "pdf.split", listOf(Raw("input"), Raw("outputDir"), opts))
            body.warnings("result")
            body.line("result.paths.forEach((path) => console.log(path));")
        }

        private fun toImages(options: ToolOptions.ToImages) {
            val password = single()
            body.checkPasswords()
            val jpeg = options.format == PdfContract.FORMAT_JPEG
            body.let("name", OutputNames.stem(input.name))
            body.let("extension", if (jpeg) "jpg" else "png")
            body.call("doc", "pdf.open", listOf(Raw("input"), password.ifEmpty { null }))
            val render = linkedMapOf<String, Any?>("dpi" to options.dpi, "format" to options.format)
            if (jpeg) render["quality"] = PdfToolRunner.JPEG_QUALITY
            body.closing("doc") {
                // The tool pads page numbers to at least two digits. zh-CN: 工具把页码补足到至少两位.
                body.line("let width = Math.max(2, String(doc.pageCount).length);")
                if (options.pages != null) {
                    body.helpers += PAGES_OF
                    body.let("pages", Raw("pagesOf(${Js.string(options.pages)}, doc.pageCount)"))
                    body.line("for (let index = 0; index < pages.length; index++) {")
                } else {
                    body.line("for (let page = 1; page <= doc.pageCount; page++) {")
                }
                body.indent {
                    if (options.pages != null) body.line("let page = pages[index];")
                    body.line("let path = outputDir + '/' + name + '-p' + String(page).padStart(width, '0') + '.' + extension;")
                    body.call(null, "doc.renderToFile", listOf(Raw("page"), Raw("path"), render))
                    body.line("console.log(path);")
                }
                body.line("}")
            }
        }

        private fun fromImages(options: ToolOptions.FromImages) {
            body.paths("inputs", request.inputs.map { it.file })
            body.path("output", request.output)
            val opts = linkedMapOf<String, Any?>(
                "pageSize" to options.pageSize,
                "orientation" to options.orientation,
                "margin" to options.margin,
            )
            body.call("result", "pdf.fromImages", listOf(Raw("inputs"), Raw("output"), opts))
            finish()
        }

        private fun encrypt() {
            val opts = LinkedHashMap(single())
            opts["userPassword"] = body.password("newPassword", "The password that will open the result. $FILL_IN")
            opts["keyLength"] = request.keyLength
            body.checkPasswords()
            body.call("result", "pdf.encrypt", listOf(Raw("input"), Raw("output"), opts))
            finish()
        }

        private fun decrypt() {
            val opts = single()
            body.checkPasswords()
            body.call("result", "pdf.decrypt", listOf(Raw("input"), Raw("output"), opts.ifEmpty { null }))
            finish()
        }

        private fun extractText(options: ToolOptions.ExtractText) {
            val opts = LinkedHashMap<String, Any?>()
            options.pages?.let { opts["pages"] = it }
            opts += single()
            body.checkPasswords()
            val arguments = listOf(Raw("input"), opts.ifEmpty { null })
            // The tool puts a line break between pages. zh-CN: 工具在页与页之间加一个换行.
            when (body.style) {
                ScriptStyle.RHINO -> {
                    body.call("texts", "pdf.text", arguments)
                    body.line("files.ensureDir(output);")
                    body.line("files.write(output, texts.join('\\n'));")
                }
                ScriptStyle.NODE -> {
                    body.notes += "Writing the text file uses fs of the Node.js runtime, which needs its storage permission."
                    body.call("{ texts }", "pdf.text", arguments)
                    body.line("let fs = require('fs');")
                    body.line("await fs.promises.mkdir(require('path').dirname(output), { recursive: true });")
                    body.line("await fs.promises.writeFile(output, texts.join('\\n'));")
                }
                ScriptStyle.BUN -> {
                    body.notes += "Writing the text file uses Bun.write of the Bun runtime, which needs its storage permission."
                    body.call("{ texts }", "pdf.text", arguments)
                    body.line("await Bun.write(output, texts.join('\\n'));")
                }
            }
            body.line("console.log(output);")
        }

        private fun organize(options: ToolOptions.Organize) {
            val placed = options.pages
            val angles = placed.map { Math.floorMod(it.rotation, FULL_TURN) }.filter { it != 0 }.distinct().sorted()
            val password = single()
            body.checkPasswords()
            body.call("doc", "pdf.open", listOf(Raw("input"), password.ifEmpty { null }))
            // Page numbers of save() are those of the opened document. zh-CN: save() 的页码按打开的文档计.
            val save = linkedMapOf<String, Any?>(
                "pages" to PageRanges.format(placed.map { it.page }.toIntArray()),
                "order" to placed.map { it.page },
            )
            angles.firstOrNull()?.let { angle ->
                save["rotate"] = linkedMapOf("degrees" to angle, "pages" to turned(placed, angle) { it.value.page })
            }
            body.line("let result;")
            body.closing("doc") {
                body.call("result", "doc.save", listOf(Raw("output"), save), declare = false)
            }
            body.warnings("result")
            angles.drop(1).forEachIndexed { index, angle ->
                // Later turns name positions in the result, which is both their input and output. zh-CN: 之后的旋转按结果中的位置计, 结果既是输入也是输出.
                val name = "turned${index + 1}"
                body.call(name, "pdf.rotate", listOf(Raw("output"), Raw("output"), angle, mapOf("pages" to turned(placed, angle) { it.index + 1 })))
                body.warnings(name)
            }
            body.line("console.log(output);")
        }

        private fun watermark(options: ToolOptions.Watermark) {
            val image = options.type == PdfContract.STAMP_IMAGE
            val opts = LinkedHashMap<String, Any?>()
            if (image) {
                body.path("image", request.image ?: ScriptFile(ScriptPaths.GUESS_FOLDER + "/image.png", guessed = true))
                opts["image"] = Raw("image")
            } else {
                opts["text"] = options.text
            }
            opts["position"] = options.position
            opts["rotation"] = options.rotation
            opts["opacity"] = options.opacity
            if (options.tile) opts["tile"] = true
            if (image) {
                options.width?.let { opts["width"] = it }
            } else {
                opts["color"] = options.color ?: ToolPayloads.WATERMARK_COLOR
                options.fontSize?.let { opts["fontSize"] = it }
            }
            if (options.layer != PdfContract.LAYER_OVER) opts["layer"] = options.layer
            options.pages?.let { opts["pages"] = it }
            opts += single()
            body.checkPasswords()
            body.call("result", "pdf.watermark", listOf(Raw("input"), Raw("output"), opts))
            finish()
        }

        private fun pageNumbers(options: ToolOptions.PageNumbers) {
            val opts = LinkedHashMap<String, Any?>()
            if (options.format == null || options.start in 1..MAX_START) {
                options.format?.let { format ->
                    opts["pageNumbers"] = linkedMapOf("format" to format, "position" to options.position, "start" to options.start)
                }
                slotsOf(options.header)?.let { opts["header"] = it }
                slotsOf(options.footer)?.let { opts["footer"] = it }
                opts["fontSize"] = options.fontSize
                options.pages?.let { opts["pages"] = it }
            } else {
                // pageNumbers.start counts from 1; other starts need complete items. zh-CN: pageNumbers.start 从 1 起; 其他起始号需要完整条目.
                opts["items"] = pageNumberItems(options)
            }
            opts += single()
            body.checkPasswords()
            body.call("result", "pdf.stamp", listOf(Raw("input"), Raw("output"), opts))
            finish()
        }

        private fun compress(options: ToolOptions.Compress) {
            val preset = CompressState.numbersOf(options.preset)
            val opts = linkedMapOf<String, Any?>("preset" to options.preset)
            if (options.imageDpi != preset.imageDpi) opts["imageDpi"] = options.imageDpi
            if (options.imageQuality != preset.imageQuality) opts["imageQuality"] = options.imageQuality
            opts["removeMetadata"] = options.removeMetadata
            opts["objectStreams"] = options.objectStreams
            opts += single()
            body.checkPasswords()
            body.call("result", "pdf.compress", listOf(Raw("input"), Raw("output"), opts))
            finish()
        }

        private fun fillForm(options: ToolOptions.FillForm) {
            val opts = LinkedHashMap<String, Any?>()
            if (options.flatten) opts["flatten"] = true
            opts += single()
            body.checkPasswords()
            val values = options.values.filterKeys { it != KEY_ON_PROGRESS }
            if (values.size != options.values.size) {
                body.notes += "A field named onProgress cannot be filled from a script (the name means the progress callback); it is left out."
            }
            objectOf("values", values)
            body.call("result", "pdf.fillForm", listOf(Raw("input"), Raw("output"), Raw("values"), opts.ifEmpty { null }))
            finish()
        }

        private fun properties(options: ToolOptions.Properties) {
            val password = single()
            body.checkPasswords()
            if (options.info.isNotEmpty() || !options.clearOutline) {
                objectOf("info", options.info)
                body.call("result", "pdf.setInfo", listOf(Raw("input"), Raw("output"), Raw("info"), password.ifEmpty { null }))
                body.warnings("result")
                if (options.clearOutline) {
                    // The written output is no longer encrypted. zh-CN: 写出的结果已不再加密.
                    body.call("cleared", "pdf.setOutline", listOf(Raw("output"), Raw("output"), emptyList<Any>()))
                    body.warnings("cleared")
                }
            } else {
                body.call("result", "pdf.setOutline", listOf(Raw("input"), Raw("output"), emptyList<Any>(), password.ifEmpty { null }))
                body.warnings("result")
            }
            body.line("console.log(output);")
        }

        /**
         * `let name = { ... };` of user keys: a `__proto__` key is defined as an own property, which a literal cannot do.
         * zh-CN: 由用户给出的键组成的 `let name = { ... };`: `__proto__` 键以自有属性定义, 字面量做不到.
         */
        private fun objectOf(name: String, values: Map<String, Any?>) {
            body.let(name, values.filterKeys { it != PROTO })
            if (PROTO in values) {
                val value = Js.inline(values[PROTO])
                body.line("Object.defineProperty($name, '$PROTO', { value: $value, enumerable: true, writable: true, configurable: true });")
            }
        }

        /**
         * The `stamp` items of page numbers that do not start from 1: the same items as [ToolPayloads.pageNumberItems].
         * zh-CN: 页码不从 1 起时的 `stamp` 条目, 与 [ToolPayloads.pageNumberItems] 相同.
         */
        private fun pageNumberItems(options: ToolOptions.PageNumbers): List<Map<String, Any?>> {
            fun item(text: String, position: String, offset: Int?) = linkedMapOf<String, Any?>("type" to PdfContract.STAMP_TEXT, "text" to text, "position" to position).apply {
                offset?.let { put("pageOffset", it) }
                put("fontSize", options.fontSize)
                options.pages?.let { put("pages", it) }
            }
            val items = ArrayList<Map<String, Any?>>()
            options.format?.let { items += item(it, options.position, ToolPayloads.pageOffset(options.start, options.pages)) }
            listOf(options.header to TOP_ROW, options.footer to BOTTOM_ROW).forEach { (slots, row) ->
                listOf(slots.left, slots.center, slots.right).zip(row).forEach { (text, position) -> if (text.isNotBlank()) items += item(text, position, null) }
            }
            return items
        }

        private fun slotsOf(slots: ToolOptions.Slots): Map<String, String>? {
            if (slots.blank) return null
            return linkedMapOf("left" to slots.left, "center" to slots.center, "right" to slots.right).filterValues { it.isNotBlank() }.ifEmpty { null }
        }

        private fun turned(placed: List<OrganizedPage>, angle: Int, page: (IndexedValue<OrganizedPage>) -> Int): String =
            PageRanges.format(placed.withIndex().filter { Math.floorMod(it.value.rotation, FULL_TURN) == angle }.map(page).toIntArray())

    }

