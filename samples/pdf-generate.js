/**
 * 图片文字与 HTML 转 PDF [v6.8.1+]
 *
 * pdf 模块由 3-Paper PDF 插件提供, 先在插件中心安装并启用.
 * 演示:
 * 1. pdf.fromImages 把多张图片 (png, jpeg, webp 等) 做成 PDF, 每张一页. pageSize 为 'fit' (默认, 页面与图片同大), 'A4', 'Letter'
 *    或 [宽, 高] (单位为点); fit 为 'contain' (完整放入, 默认) 或 'cover' (铺满裁切); margin 为页边距 (点);
 *    orientation 为 'auto', 'portrait' 或 'landscape'; quality 为 1-100 (按 JPEG 压缩) 或 'lossless'.
 * 2. pdf.fromText 把纯文本排成 PDF, 按行自动换页. 选项 pageSize, margin, fontSize (默认 12), lineSpacing, title;
 *    需要特定字体时用 fontPath 指定 TrueType / OpenType 字体文件.
 * 3. pdf.fromHtml 把 HTML 字符串或 HTML 文件排成 PDF. 页面不加载任何网络资源与本地文件 (被拦下的网络请求记在返回值的
 *    warnings 里), 图片请用 data: URL 内嵌; 页面中的 JavaScript 默认执行, javaScript: false 关闭; timeout 为整个转换的
 *    最长毫秒数 (默认一直等到页面加载完成).
 * 返回值含输出路径 path, 页数 pageCount, 字节数 sizeBytes 与提示 warnings.
 * 可选参数 (engines.execScriptFile 的 arguments): path 为提供图片的 PDF (默认为样例 fixtures/outline.pdf, 找不到时现场生成),
 * outDir 为输出目录 (默认为 /sdcard/Documents/3-Paper PDF/samples/generate), output 为写入结果摘要 (JSON) 的文件.
 */

let args = engines.myEngine().execArgv;
let base = files.join(files.getSdcardPath(), 'Documents', '3-Paper PDF');
let outDir = args.outDir ? String(args.outDir) : files.join(base, 'samples', 'generate');
let summary = { errors: [] };

function fixture(name) {
    let local = files.path('./fixtures/' + name);
    if (files.exists(local)) return local;
    let shared = files.join(base, 'fixtures', name);
    return files.exists(shared) ? shared : null;
}

function outPath(name) {
    let path = files.join(outDir, name);
    files.ensureDir(path);
    return path;
}

function report(label, e) {
    console.error(label + ' 失败 [' + (e.code || e.name) + ']: ' + e.message);
    summary.errors.push(label + ': ' + (e.code || e.name));
}

if (!pdf.isAvailable()) {
    summary.errors.push('PLUGIN_UNAVAILABLE');
    console.error('3-Paper PDF 插件未安装或未启用, 请先在插件中心安装并启用.');
} else {
    /* 1. 图片转 PDF. 这里先把一个 PDF 的前两页渲染成 png 与 jpeg 作为图片素材, 实际使用时换成自己的图片路径即可. */
    try {
        let source = args.path ? String(args.path) : fixture('outline.pdf')
            || pdf.fromText('Picture one\n\nA page used as an image.', outPath('demo-source.pdf')).path;
        let pageCount = pdf.info(source).pageCount;
        let png = pdf.renderToFile(source, 1, outPath('picture-1.png'), { dpi: 96 });
        let jpeg = pdf.renderToFile(source, Math.min(2, pageCount), outPath('picture-2.jpg'), { dpi: 96, format: 'jpeg', quality: 85 });
        let album = pdf.fromImages([png.path, jpeg.path], outPath('album.pdf'), { pageSize: 'A4', fit: 'contain', margin: 24 });
        let fitted = pdf.fromImages([png.path], outPath('album-fit.pdf'), { quality: 'lossless' });
        let fittedPage = pdf.info(fitted.path).pages[0];
        summary.fromImages = { pageCount: album.pageCount, sizeBytes: album.sizeBytes, fitPage: Math.round(fittedPage.width) + 'x' + Math.round(fittedPage.height) };
        console.log('fromImages (A4):', album.pageCount, '页 |', album.sizeBytes, '字节 ->', album.path);
        console.log('fromImages (fit, 无损): 页面', summary.fromImages.fitPage, '点');
    } catch (e) {
        report('pdf.fromImages', e);
    }

    /* 2. 文本转 PDF. 文本较长时自动换页. */
    try {
        let lines = ['Meeting notes', ''];
        for (let i = 1; i <= 80; i++) {
            lines.push(i + '. The quick brown fox jumps over the lazy dog.');
        }
        let notes = pdf.fromText(lines.join('\n'), outPath('notes.pdf'), { pageSize: 'Letter', fontSize: 14, margin: 48, title: 'Meeting notes' });
        summary.fromText = { pageCount: notes.pageCount, title: pdf.info(notes.path).title };
        console.log('fromText:', notes.pageCount, '页 | 标题:', summary.fromText.title, '->', notes.path);
    } catch (e) {
        report('pdf.fromText', e);
    }

    /* 3. HTML 转 PDF: 先用字符串, 再用文件 (图片用 data: URL 内嵌). */
    try {
        let html = '<h1>Weekly report</h1>'
            + '<p id="date">Generated by 3-Paper PDF.</p>'
            + '<table border="1" cellpadding="6"><tr><th>Item</th><th>Count</th></tr>'
            + '<tr><td>Pages</td><td>12</td></tr><tr><td>Images</td><td>3</td></tr></table>'
            + '<script>document.getElementById("date").textContent += " (script ran)";</script>';
        let weekly = pdf.fromHtml(html, outPath('report.pdf'), { pageSize: 'A4', margin: 36 });
        let noScript = pdf.fromHtml(html, outPath('report-no-js.pdf'), { javaScript: false });
        let ran = pdf.text(weekly.path, { pages: [1] })[0].indexOf('script ran') >= 0;
        let skipped = pdf.text(noScript.path, { pages: [1] })[0].indexOf('script ran') < 0;

        let thumb = pdf.render(weekly.path, 1, { width: 240 });
        let picture;
        try {
            picture = 'data:image/png;base64,' + images.toBase64(thumb, 'png');
        } finally {
            thumb.recycle();
        }
        let page = outPath('page.html');
        files.write(page, '<h2>From a file</h2><p>The picture below is embedded as a data URL.</p><img src="' + picture + '">'
            + '<p><img src="https://example.com/remote.png" alt="remote images are not loaded"></p>');
        let fromFile = pdf.fromHtml(page, outPath('page.pdf'));
        summary.fromHtml = {
            pageCount: weekly.pageCount, scriptRan: ran, scriptSkipped: skipped,
            filePages: fromFile.pageCount, fileWarnings: fromFile.warnings.length,
        };
        console.log('fromHtml (字符串):', weekly.pageCount, '页 | 执行了脚本:', ran, '| javaScript: false 时未执行:', skipped);
        console.log('fromHtml (文件):', fromFile.pageCount, '页 ->', fromFile.path);
        fromFile.warnings.forEach(w => console.log('  提示:', w));
    } catch (e) {
        report('pdf.fromHtml', e);
    }
}

if (args.output) {
    files.write(String(args.output), JSON.stringify(summary));
}
